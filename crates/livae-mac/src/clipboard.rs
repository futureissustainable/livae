//! Clipboard history on its own shortcut (Hyper+V by default).
//!
//! Watching: the pasteboard's change count is checked every 0.4 s; copies marked concealed or transient (password
//! managers, generated content) are never kept. Text, code, links, colours, images and files are stored in
//! `~/Library/Application Support/Livae/clipboard.json`, images as PNG files in `clips/`.
//!
//! Showing: one glass list at the text cursor (else at the mouse), images inline as thumbnails. Enter, a click or
//! ⌘1-⌘9 puts the item back on the clipboard and, with the Accessibility permission, pastes it into the app in
//! front with ⌘V. ⌘P pins, ⌘⌫ deletes, Esc closes.

